/** Deterministic compact build from frozen uniform source extracts; no network. */
import fs from 'node:fs';
import crypto from 'node:crypto';
import zlib from 'node:zlib';
import {spellingIdentity} from '../static/spelling-equivalence.mjs';
const hash=x=>crypto.createHash('sha256').update(x).digest('hex');
const frequency=JSON.parse(fs.readFileSync('reports/rare-word-contact/frequency.json'));
const sources=JSON.parse(fs.readFileSync('reports/contact-live/lexicon-sources.json'));
const frequencies=new Map();
for(const [word,value]of Object.entries(frequency.zipf)){const w=spellingIdentity(word);frequencies.set(w,Math.max(frequencies.get(w)??0,value));}
const words=[...frequencies.keys()].sort(),index=new Map(words.map((w,i)=>[w,i]));
if(words.length>=65536)throw Error('Contact lexicon requires a wider index.');
const pairs=new Map();
for(const [source,record]of sources.sources.entries())for(const term of record.terms){
  const ids=term.split(' ').map(w=>index.get(spellingIdentity(w))).sort((a,b)=>a-b);
  if(ids.some(i=>i==null)||ids[0]===ids[1])continue;
  const key=ids[0]*65536+ids[1];pairs.set(key,(pairs.get(key)??0)|(1<<source));
}
const keys=[...pairs.keys()].sort((a,b)=>a-b),zipf=Buffer.alloc(words.length*2),packed=Buffer.alloc(keys.length*4);
words.forEach((w,i)=>zipf.writeUInt16LE(Math.round(frequencies.get(w)*100),i*2));
keys.forEach((k,i)=>packed.writeUInt32LE(k,i*4));
const payload={words:words.join('\n'),zipf:zipf.toString('base64'),pairs:packed.toString('base64'),sources:Buffer.from(keys.map(k=>pairs.get(k))).toString('base64')};
const text='/** Generated by scripts/build-contact-data.mjs. See CONTACT-SOURCES.md. */\nexport default '+JSON.stringify(payload)+';\n';
fs.writeFileSync('static/contact-data.mjs',text);
const manifest={model_sha256:sources.model_sha256,wordfreq_version:frequency.version,words:words.length,pairs:keys.length,
  source_counts:sources.sources.map((s,i)=>({name:s.name,terms:s.terms.length,pairs:keys.filter(k=>pairs.get(k)&(1<<i)).length,additionalPairs:keys.filter(k=>(pairs.get(k)&(1<<i))&&!(pairs.get(k)&((1<<i)-1))).length})),
  bytes:Buffer.byteLength(text),gzip_bytes:zlib.gzipSync(text).length,sha256:hash(text),frequency_sha256:hash(fs.readFileSync('reports/rare-word-contact/frequency.json')),extract_sha256:hash(fs.readFileSync('reports/contact-live/lexicon-sources.json'))};
fs.writeFileSync('reports/contact-live/data-manifest.json',JSON.stringify(manifest,null,2)+'\n');console.log(JSON.stringify(manifest,null,2));
