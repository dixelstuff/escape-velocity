"""Conservative, inspectable lexical evidence for diagnostics only (never shot legality)."""
from pathlib import Path
from zipfile import ZipFile
from collections import defaultdict
import json
ROOT=Path(__file__).resolve().parents[1]
def main():
    config=json.loads((ROOT/'static/model/config.json').read_text())
    vocabulary=set(json.loads((ROOT/'static/model'/config['words_file']).read_text()))
    synsets,links,lemmas={},[],defaultdict(set)
    with ZipFile(ROOT/'data/wordnet.zip') as archive:
        for part in ['noun','verb','adj','adv']:
            for raw in archive.read('wordnet/data.'+part).decode().splitlines():
                if not raw or not raw[0].isdigit():continue
                f=raw.split(' | ')[0].split();count=int(f[3],16);cursor=4+2*count;pos='a' if f[2]=='s' else f[2];key=(f[0],pos)
                synsets[key]=[f[4+2*i].split('(')[0] for i in range(count)]
                for w in synsets[key]:lemmas[pos].add(w)
                for i in range(int(f[cursor])):
                    symbol,offset,target_pos,indices=f[cursor+1+4*i:cursor+5+4*i]
                    if symbol=='+' and indices!='0000':links.append((key,int(indices[:2],16)-1,(offset,target_pos),int(indices[2:],16)-1))
        exceptions={part:archive.read('wordnet/'+part+'.exc').decode().splitlines() for part in ['noun','verb','adj','adv']}
    def prefix(a,b):
        n=0
        for x,y in zip(a,b):
            if x!=y:break
            n+=1
        return n
    # Explicit derivation pointers can link very different spellings (e.g. avian/bird).
    # Require shared orthography too: semantic relatedness alone is not morphology.
    pairs={};derived=defaultdict(set)
    for source,i,target,j in links:
        if target not in synsets:continue
        a,b=synsets[source][i],synsets[target][j]
        if a==b:continue
        derived[a].add(b);derived[b].add(a)
        if a in vocabulary and b in vocabulary and min(len(a),len(b))>=4 and prefix(a,b)>=3:
            pairs[tuple(sorted((a,b)))]='wordnet derivation'
    # Attested inflections: dictionary base + standard WordNet detachment rules.
    roots=defaultdict(set)
    rules={'n':[('s',''),('ses','s'),('ves','f'),('xes','x'),('zes','z'),('ches','ch'),('shes','sh'),('men','man'),('ies','y')], 'v':[('s',''),('ies','y'),('es','e'),('es',''),('ed','e'),('ed',''),('ing','e'),('ing','')], 'a':[('er',''),('est',''),('er','e'),('est','e')],'r':[]}
    for pos,forms in lemmas.items():
        for word in vocabulary:
            if word in forms:roots[(pos,word)].add(word)
            for suffix,replacement in rules[pos]:
                if word.endswith(suffix):
                    base=word[:-len(suffix)]+replacement
                    if len(base)>=3 and base in forms:roots[(pos,base)].add(word)
    for part,rows in exceptions.items():
        pos={'noun':'n','verb':'v','adj':'a','adv':'r'}[part]
        for row in rows:
            word,*bases=row.split()
            if word in vocabulary:
                for base in bases:
                    if base in vocabulary:roots[(pos,base)].add(word);roots[(pos,base)].add(base)
    for group in roots.values():
        for a in group:
            for b in group:
                if a<b and min(len(a),len(b))>=3 and prefix(a,b)>=3:pairs.setdefault((a,b),'dictionary inflection')
    # Conservative agent/place derivation: agent must have a WordNet derivation
    # to a verb; place must be an attested noun in -ery with the same base.
    for place in vocabulary & lemmas['n']:
        if not place.endswith('ery'):continue
        stem=place[:-3]
        for base in [stem,stem+'e']:
            if len(base)<3 or base not in lemmas['v']:continue
            for agent in derived[base]:
                if agent in vocabulary and agent.endswith('er') and prefix(agent,place)>=3:
                    pairs.setdefault(tuple(sorted((agent,place))),'attested agent/place derivation')
    names=sorted({w for pair in pairs for w in pair});indices={w:i for i,w in enumerate(names)}
    kinds=sorted(set(pairs.values()))
    entries=[[indices[a],indices[b],kinds.index(kind)] for (a,b),kind in sorted(pairs.items())]
    (ROOT/'static/lexical-relations.mjs').write_text('''/** WordNet 3.0 derivations + dictionary-checked inflections/agent-place forms.
 * Generated by scripts/build_lexical_relations.py. Diagnostics only.
 * Princeton WordNet license: https://wordnet.princeton.edu/license-and-commercial-use
 */
const words='''+json.dumps(names,separators=(',',':'))+''';
const kinds='''+json.dumps(kinds)+''';
const entries='''+json.dumps(entries,separators=(',',':'))+''';
const relations=new Map(entries.map(([a,b,evidence])=>[[words[a],words[b]].sort().join('\\0'),kinds[evidence]]));
export const LEXICAL_VERSION='dictionary-morphology-v1';
export function lexicalRelation(a,b){
 if(a===b)return null;
 const evidence=relations.get([a,b].sort().join('\\0'));
 return evidence?{from:a,to:b,evidence,confidence:evidence==='attested agent/place derivation'?'probable':'dictionary-supported',creativity_factor:.1}:null;
}
''')
    with ZipFile(ROOT/'data/wordnet.zip') as archive:(ROOT/'static/WORDNET-LICENSE.txt').write_bytes(archive.read('wordnet/LICENSE'))
    print(f'Wrote {len(entries)} lexical pairs; game word-form allowances untouched.')
if __name__=='__main__':main()
