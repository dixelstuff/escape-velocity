import assert from 'node:assert/strict';
import {attemptNotice,usefulForwardMiss,intendedGain,entryNotice} from '../static/play-feedback.mjs';
import {successOutcome} from '../static/success-mode.mjs';
const state={start:'coffee',current:'heat',target:'science',baseline:0,threshold:.3,progress:.1,history:[{word:'heat',origin:'coffee',attempt:1,success:true,destination:.1}]};
const event={outcome:'miss',word:'science',origin:'heat',attempt:2,destination:.2};
assert.equal(attemptNotice(event,'science',state),'Miss! SCIENCE needs a stronger link to HEAT.');
assert.ok(usefulForwardMiss(event,state));assert.equal(intendedGain(event,state),.1);
assert.equal(attemptNotice({...event,destination:.11},'science',state),'Miss! Not enough connection.');
assert.equal(attemptNotice({...event,destination:.09},'science',state),'Miss! Not enough connection.','a tiny backward weak swing is also nearby');
assert.equal(attemptNotice({...event,word:'speak',origin:'talk',outcome:'water'},'chirp',state),'Miss! SPEAK takes you away from CHIRP.');
assert.equal(attemptNotice({...event,word:'cold',destination:.05},'science',state),'Miss! COLD takes you away from SCIENCE.');
assert.equal(attemptNotice({outcome:'landed'},'science',state),'Par is out of reach. Try again.');
assert.equal(usefulForwardMiss({...event,destination:.13},state),true,'inclusive 10% of original gap');
assert.equal(usefulForwardMiss({...event,destination:.129},state),false);
assert.equal(usefulForwardMiss({...event,outcome:'water'},state),false);
assert.equal(usefulForwardMiss({...event,outcome:'landed',success:true},state),false);
assert.equal(usefulForwardMiss(event,{...state,threshold:0}),false);
assert.equal(entryNotice(Error('That word is outside the supported vocabulary. No shot used.'),'heat'),'Word not allowed. Try another.');
assert.equal(entryNotice(Error('The ball is already on that word. No shot used.'),'heat'),'You’re already on HEAT. Try another word.');
assert.equal(entryNotice(Error('Connection failed'),'heat'),'Connection failed');
assert.equal(successOutcome({attempts:3,challenge:{par:3,attempt:4}}),'Par on attempt 4');
assert.equal(successOutcome({attempts:2,challenge:{par:3,attempt:2}}),'Birdie on attempt 2');
console.log('Feedback passed: forward/near/backward classification, raw relative threshold, exact copy and uncharged input errors.');
