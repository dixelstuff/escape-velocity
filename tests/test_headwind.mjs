import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Embeddings,Game,decodeHalf,restoreGame} from '../static/engine.mjs';
import {withHeadwind,headwindSettings} from '../static/headwind.mjs';
import {assessHole} from '../static/assessment.mjs';
import {SkillAnalyser,skillHistoryKey} from '../static/skill.mjs';
import {reviewRoute} from '../static/route-review.mjs';
import {puzzleKey} from '../static/bridge-feedback.mjs';
import {restartSettings} from '../static/startup.mjs';
import {FlightLog,journeyText} from '../static/flight-log.mjs';
const tiny=new Embeddings(['wind','a','b'],Float32Array.from([1,0,1,1,-1,1]),2),wind={word:'wind',strength:.5};
const transformed=withHeadwind(tiny,wind);
assert.ok(Math.abs(transformed.cosine('a','b')-.6)<1e-6,'projection removes half the topic component and normalises both words');
assert.ok(Math.abs(transformed.cosine('a','a')-1)<1e-6);
assert.equal(transformed.cosine('a','b'),transformed.cosine('b','a'));
assert.equal(tiny.cosine('a','b'),0,'source model stays unchanged');
assert.equal(withHeadwind(tiny,wind),transformed,'reuse one transformed model');
assert.equal(withHeadwind(transformed,wind),transformed,'do not project twice');
assert.throws(()=>headwindSettings({word:'wind',strength:1}));
assert.throws(()=>withHeadwind(tiny,{word:'missing',strength:.5}));
const dir=new URL('../static/model/',import.meta.url),config=JSON.parse(readFileSync(new URL('config.json',dir))),raw=readFileSync(new URL(config.vector_fallback,dir));
const e=new Embeddings(JSON.parse(readFileSync(new URL(config.words_file,dir))),decodeHalf(raw.buffer.slice(raw.byteOffset,raw.byteOffset+raw.byteLength)),config.dimensions,new Uint8Array(readFileSync(new URL(config.hub_file,dir))));
const p=config.puzzles.find(p=>p.start==='gold'&&p.target==='hover'&&p.headwind),normal=config.puzzles.find(p=>p.start==='gold'&&p.target==='hover'&&!p.headwind);
assert.ok(p&&normal,'both menu variants remain available');
const g=new Game(e,p.start,p.target,p.threshold,p),plain=new Game(e,normal.start,normal.target,normal.threshold,normal);
assert.notEqual(g.baseline,plain.baseline);
assert.ok(g.e.cosine('gold','money')<e.cosine('gold','money'));
assert.ok(Math.abs(g.e.cosine('gold','silver')-e.cosine('gold','silver'))<.002);
assert.equal(new Game(e,p.start,p.target,p.threshold,p).submit(p.target).won,false);
const shot=g.submit('shiny');assert.equal(shot.success,true);assert.equal(g.won,true);
assert.equal(shot.launch,g.e.cosine('gold','shiny'));
assert.deepEqual(restoreGame(e,g.state()).state(),g.state(),'replay uses the exact saved transformation');
assert.notEqual(skillHistoryKey(g.state()),skillHistoryKey({...g.state(),headwind:undefined}));
assert.notEqual(puzzleKey(g.state()),puzzleKey({...g.state(),headwind:undefined}));
assert.deepEqual(restartSettings(g.state(),normal).headwind,g.headwind);
assert.equal(reviewRoute(e,g.state()).complete,true);
const preview=assessHole(e,p),legal=[];
for(const word of e.words){if(word===p.start)continue;const test=new Game(e,p.start,p.target,p.threshold,p);if(test.submit(word).won)legal.push(word);}
assert.deepEqual(preview.opening_bridges.map(b=>b.word).sort(),legal.sort(),'spoilers exactly match adjusted gameplay across the full vocabulary');
assert.deepEqual(preview.settings.headwind,g.headwind);
const report=new SkillAnalyser(e).analyse(g.state());assert.equal(report.complete,true);assert.equal(report.shots[0].contact,shot.launch);
const memory=new Map(),log=new FlightLog({getItem:k=>memory.get(k),setItem:(k,v)=>memory.set(k,v)});const round=log.begin(g.state(),'test');
assert.equal(log.recordSkill(round.id,report),true);assert.match(journeyText(round),/Headwind: finance/);
assert.deepEqual(new FlightLog(log.storage).active.state.headwind,g.headwind);
console.log('Headwind passed: fixed normalised projection, source isolation, symmetric geometry, separate variants, exact replay, exhaustive bridge legality, skill, shortcuts and scorecard persistence.');
