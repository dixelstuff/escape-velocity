import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Game,Embeddings,decodeHalf,restoreGame} from '../static/engine.mjs';
import {assessHole} from '../static/assessment.mjs';
import {chipRange} from '../static/chip-range.mjs';
import {FlightLog} from '../static/flight-log.mjs';
import {skillHistoryKey,SkillAnalyser} from '../static/skill.mjs';
import {reviewRoute} from '../static/route-review.mjs';
import {startupAction} from '../static/startup.mjs';
const positions={tee:.05,near:.18,hub:.18,short:.11,weak:.18,water:-.1,flag:1};
const e={index:new Map(Object.keys(positions).map(w=>[w,0])),hub:w=>w==='hub'?1:0,cosine(a,b){return a===b?1:a==='flag'?positions[b]:b==='flag'?positions[a]:a==='weak'||b==='weak'?.01:.6;}};
const settings={mode:'distance',launch_min:.1,launch_max:.22,finish_mode:'range'};
const fresh=()=>new Game(e,'tee','flag',.27,settings);
let g=fresh(),event=g.submit('near');
assert.equal(event.inside,false);assert.equal(event.won,true);assert.equal(event.finish_reason,'range');
assert.equal(event.automatic_shot.outcome,'chip');assert.equal(event.automatic_shot.attempt,2);
assert.deepEqual(g.route,['tee','near','flag']);assert.equal(g.state().attempts,2);
assert.ok(event.automatic_shot.launch>=event.automatic_shot.required);
assert.deepEqual(restoreGame(e,g.state()).state(),g.state());
const store=new Map(),log=new FlightLog({getItem:k=>store.get(k),setItem:(k,v)=>store.set(k,v)});
g=fresh();log.begin(g.state(),'fixture');event=g.submit('near');log.record('near',g.state(),event);
assert.equal(log.active.entries.length,2);assert.equal(log.active.entries[1].event.automatic,true);
assert.equal(new FlightLog(log.storage).active.state.finish_mode,'range');
for(const word of ['short','weak','water']){
 g=fresh();event=g.submit(word);assert.equal(g.won,false,word);assert.equal(g.automatic_shots.length,0,word);
 assert.deepEqual(restoreGame(e,g.state()).state(),g.state());
}
g=fresh();g.submit('short');assert.equal(g.submit('tee').won,false,'returning to the tee cannot auto finish');
const old=new Game(e,'tee','flag',.27,{...settings,finish_mode:'green'});assert.equal(old.submit('near').won,false);
assert.equal(old.submit('flag').won,true);assert.equal(old.automatic_shots.length,0,'historical manual chip stays manual');
assert.notEqual(skillHistoryKey(old.state()),skillHistoryKey({...old.state(),finish_mode:'range'}));
const envelope=chipRange(fresh());positions.near=positions.hub=(envelope.first+envelope.last)/2;
g=fresh();assert.equal(g.submit('near').won,true);g=fresh();assert.equal(g.submit('hub').won,false,'hub-adjusted contact determines the finish');
const root=new URL('../static/model/',import.meta.url),config=JSON.parse(readFileSync(new URL('config.json',root))),words=JSON.parse(readFileSync(new URL(config.words_file,root))),raw=readFileSync(new URL(config.vector_fallback,root));
const actual=new Embeddings(words,decodeHalf(raw.buffer.slice(raw.byteOffset,raw.byteOffset+raw.byteLength)),config.dimensions,new Uint8Array(readFileSync(new URL(config.hub_file,root))));
g=new Game(actual,'mars','clarity',.27,settings);
const actualLog=new FlightLog({getItem:()=>null,setItem:()=>{}});actualLog.begin(g.state(),'actual');
event=g.submit('inspire');actualLog.record('inspire',g.state(),event);assert.equal(event.outcome,'miss');
event=g.submit('rover');actualLog.record('rover',g.state(),event);assert.equal(event.won,false);
event=g.submit('camera');actualLog.record('camera',g.state(),event);assert.equal(event.inside,false);assert.equal(event.won,true);assert.equal(g.state().attempts,4);
assert.deepEqual(g.route,['mars','rover','camera','clarity']);
assert.deepEqual(restoreGame(actual,g.state()).state(),g.state());
assert.equal(reviewRoute(actual,g.state()).complete,true);
const skill=new SkillAnalyser(actual).analyse(g.state());assert.equal(skill.complete,true);assert.equal(skill.shots.length,3,'automatic chip is not a player choice');
assert.equal(skill.history_key,skillHistoryKey(g.state()));
assert.equal(actualLog.recordSkill(actualLog.active.id,skill),true);assert.equal(actualLog.active.entries.length,4);
const preview=assessHole(actual,{...settings,start:'genie',target:'cinema',threshold:.27});
assert.equal(preview.settings.finish_mode,'range');assert.ok(preview.opening_bridges.some(b=>b.word==='magic'&&b.destination<.27),'spoilers include actual automatic chip-in openings');
g=new Game(actual,'morph','lineage',.27,settings);event=g.submit('evolved');assert.equal(event.automatic_shot.outcome,'putt');
assert.equal(startupAction({state:{...g.state(),finish_mode:undefined}},{finish_mode:'range'}),'upgrade');
assert.equal(startupAction({state:g.state()},{finish_mode:'range'}),'restore');
console.log('Range finish passed: real hub-adjusted legality, counted automatic chips/putts, misses and water excluded, saved-mode replay, log/skill/shortcut support and MARS camera finish.');
